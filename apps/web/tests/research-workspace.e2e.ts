  await markdown.fill('# Reading plan\n\nEdited in the file explorer.\n')
  await markdown.press('ControlOrMeta+s')
  await expect.poll(() => readFile(join(paperRecord.directory!, 'reading.md'), 'utf8')).toContain('Edited in the file explorer.')
