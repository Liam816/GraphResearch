/** Real Loader research navigation, PDF factory, independent sessions, and durable notebooks. */
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { chromium } from 'playwright'
import { expect, it, onTestFailed, onTestFinished } from 'vitest'
import { pdfFixture } from '../../../packages/client/ui-sidebar-documentpreview/tests/pdf-fixture.ts'
import { captureStableAria, compareOrRefreshGolden, launchWebScaffold, watchConsole, webSnapshotMode } from './scaffold.ts'
import { newEnglishPage, openSettings, saveFailureShot } from './support.ts'

const EXPECTED = fileURLToPath(new URL('./expected/research-workspace/paper.expected.md', import.meta.url))
const DIRECTORY_EXPECTED = fileURLToPath(new URL('./expected/research-workspace/directory.expected.md', import.meta.url))
const REORDERED_EXPECTED = fileURLToPath(new URL('./expected/research-workspace/reordered.expected.md', import.meta.url))
const SHOTS = fileURLToPath(new URL('../../../.artifacts/research-ui', import.meta.url))

it('opens topic and paper sessions, restores folded panels and drafts, and persists notes after reload', async () => {
  const scaffold = await launchWebScaffold()
  onTestFinished(() => scaffold.close())
  await scaffold.ctx.workspaceRegistry.create(scaffold.workspaceCwd)
  await writeFile(join(scaffold.workspaceCwd, 'paper.pdf'), pdfFixture(3))
  const executablePath = process.env['DSH_TEST_BROWSER_EXECUTABLE']
  const browser = await chromium.launch(executablePath === undefined ? {} : { executablePath })
  onTestFinished(() => browser.close())
  const page = await newEnglishPage(browser)
  await page.setViewportSize({ width: 1800, height: 1080 })
  const console = watchConsole(page)
  const clientErrors: string[] = []
  page.on('console', (message) => { if (message.type() === 'error') clientErrors.push(message.text()) })
  onTestFailed(() => { process.stderr.write(`${JSON.stringify({ ...console, clientErrors })}\n`) })
  onTestFailed(() => saveFailureShot(page, 'research-workspace'))
  await page.goto(scaffold.authenticatedUrl, { waitUntil: 'load' })
  const library = page.getByRole('region', { name: 'Research library', exact: true })
  const legacyWorkspaces = page.locator('[data-workspace-browser] > details')
  await legacyWorkspaces.waitFor({ state: 'attached' })
  expect(await legacyWorkspaces.isVisible()).toBe(false)
  await library.getByRole('button', { name: 'New topic', exact: true }).click()
  const topicForm = page.getByRole('dialog', { name: 'New topic', exact: true })
  await topicForm.getByLabel('Title', { exact: true }).fill('Robot VLA')
  await topicForm.getByRole('button', { name: 'Create', exact: true }).click()
  const workbench = page.locator('[data-research-workbench]')
  await workbench.getByRole('heading', { name: 'Robot VLA', exact: true }).waitFor()
  expect(await workbench.getByRole('region', { name: 'Original PDF', exact: true }).count()).toBe(0)

  const addPaper = async (title: string): Promise<void> => {
    await library.getByRole('button', { name: 'Add paper', exact: true }).click()
    const form = page.getByRole('dialog', { name: 'Add paper', exact: true })
    await form.getByLabel('Title', { exact: true }).fill(title)
    await form.getByLabel('PDF file path', { exact: true }).fill('paper.pdf')
    await form.getByRole('button', { name: 'Create', exact: true }).click()
    await expect.poll(() => workbench.locator('header strong').textContent()).toBe(title)
  }
  await addPaper('RT-2')
  await workbench.getByRole('img', { name: 'PDF page 1', exact: true }).waitFor()
  const header = workbench.locator(':scope > header')
  expect(await header.getByRole('button', { name: 'Restore three panels', exact: true }).count()).toBe(0)
  const panelControls = header.getByRole('group', { name: 'Panel visibility', exact: true })
  const pdfToggle = panelControls.getByRole('button', { name: 'Original PDF', exact: true })
  await pdfToggle.focus()
  await pdfToggle.press('Space')
  await expect.poll(() => pdfToggle.getAttribute('aria-pressed')).toBe('false')
  expect(await workbench.getByRole('region', { name: 'Original PDF', exact: true }).count()).toBe(0)
  await pdfToggle.press('Enter')
  await expect.poll(() => pdfToggle.getAttribute('aria-pressed')).toBe('true')
  await expect.poll(async () => (await workbench.getByRole('img', { name: 'PDF page 1', exact: true }).boundingBox())?.width).toBeGreaterThan(100)
  const notes = workbench.getByRole('textbox', { name: 'Learning notes', exact: true })
  await notes.fill('# RT-2\n\nUnderstand the action token representation.')
  await workbench.getByRole('button', { name: 'Save notes', exact: true }).click()
  await workbench.getByRole('status').filter({ hasText: /^Saved$/ }).waitFor()
  await expect.poll(() => workbench.getByRole('button', { name: 'Save notes', exact: true }).isDisabled()).toBe(true)
  await compareOrRefreshGolden(EXPECTED, await captureStableAria(page, '[data-research-workbench]', scaffold.workspaceCwd), webSnapshotMode())
  await compareOrRefreshGolden(DIRECTORY_EXPECTED, await captureStableAria(page, '[data-workspace-browser]', scaffold.workspaceCwd), webSnapshotMode())
  await mkdir(SHOTS, { recursive: true })
  await page.screenshot({ path: join(SHOTS, 'paper-light.png') })

  const readOrder = () => workbench.locator('[data-research-panel]').evaluateAll(panels => panels.map(panel => panel.getAttribute('data-research-panel')))
  const beginDrag = async (source: string, target: string): Promise<void> => {
    const start = await workbench.getByRole('button', { name: `Reorder ${source}`, exact: true }).boundingBox()
    const end = await workbench.getByRole('button', { name: `Reorder ${target}`, exact: true }).boundingBox()
    if (start === null || end === null) throw new Error('both panel drag handles must be visible')
    await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
    await page.mouse.down()
    await page.mouse.move(start.x + start.width / 2 + 16, start.y + start.height / 2, { steps: 3 })
    await workbench.locator('[data-panel-sorting=true]').waitFor()
    await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 10 })
    await workbench.locator('[data-drop-edge]').waitFor()
  }
  const editor = workbench.getByRole('textbox', { name: /Describe what you want to build/ })
  await editor.fill('Composer draft survives pane reordering')
  await notes.fill('Notebook draft survives pane reordering')
  const noteNode = await notes.elementHandle()
  if (noteNode === null) throw new Error('the notebook editor must be mounted')
  onTestFinished(() => noteNode.dispose())
  const editorNode = await editor.elementHandle()
  if (editorNode === null) throw new Error('the composer must be mounted')
  onTestFinished(() => editorNode.dispose())

  const pdf = workbench.getByRole('region', { name: 'Original PDF', exact: true })
  const openZoom = async (): Promise<void> => {
    const bounds = await pdf.locator('[data-document-zoom-frame]').boundingBox()
    if (bounds === null) throw new Error('the PDF zoom frame must be visible')
    await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height - 8)
    await expect.poll(() => pdf.locator('[data-document-zoom-controls]').getAttribute('data-document-zoom-visible')).toBe('true')
    await pdf.getByRole('button', { name: 'Choose zoom', exact: true }).click()
  }
  await openZoom()
  await page.getByRole('menuitem', { name: '200%', exact: true }).click()
  const scrollport = pdf.locator('[data-document-zoom-scrollport]')
  await expect.poll(() => scrollport.evaluate(node => node.scrollHeight > node.clientHeight)).toBe(true)
  await scrollport.evaluate((node) => { node.scrollTop = 100 })
  const pdfScroll = await scrollport.evaluate(node => node.scrollTop)
  const pdfNode = await scrollport.elementHandle()
  if (pdfNode === null) throw new Error('the PDF scrollport must be mounted')
  onTestFinished(() => pdfNode.dispose())

  await beginDrag('Reading notes', 'Agent chat')
  expect(await readOrder()).toEqual(['agent', 'pdf', 'notes'])
  expect(await page.locator('[data-dnd-overlay]').getByRole('textbox').count()).toBe(0)
  await page.screenshot({ path: join(SHOTS, 'paper-dragging.png') })
  await page.mouse.up()
  await expect.poll(readOrder).toEqual(['notes', 'agent', 'pdf'])
  expect(await panelControls.getByRole('button').allTextContents()).toEqual(['Reading notes', 'Agent chat', 'Original PDF'])
  expect(await notes.evaluate((node, original) => node === original, noteNode)).toBe(true)
  expect(await editor.evaluate((node, original) => node === original, editorNode)).toBe(true)
  expect(await scrollport.evaluate((node, original) => node === original, pdfNode)).toBe(true)
  expect(await notes.inputValue()).toBe('Notebook draft survives pane reordering')
  expect(await editor.textContent()).toBe('Composer draft survives pane reordering')
  expect(await scrollport.evaluate(node => node.scrollTop)).toBeCloseTo(pdfScroll, 0)

  await beginDrag('Original PDF', 'Reading notes')
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await expect.poll(() => workbench.locator('[data-panel-sorting=true]').count()).toBe(0)
  expect(await readOrder()).toEqual(['notes', 'agent', 'pdf'])

  const agentHandle = workbench.getByRole('button', { name: 'Reorder Agent chat', exact: true })
  await agentHandle.focus()
  await agentHandle.press('Space')
  await workbench.locator('[data-panel-sorting=true]').waitFor()
  await page.keyboard.press('ArrowRight')
  await workbench.locator('[data-research-panel=pdf][data-drop-edge=after]').waitFor()
  await page.keyboard.press('Space')
  await expect.poll(readOrder).toEqual(['notes', 'pdf', 'agent'])

  await workbench.getByRole('button', { name: 'Arrange Agent chat', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Move left', exact: true }).click()
  await expect.poll(readOrder).toEqual(['notes', 'agent', 'pdf'])
  await workbench.getByRole('button', { name: 'Arrange Reading notes', exact: true }).click()
  expect(await page.getByRole('menuitem', { name: 'Move left', exact: true }).isDisabled()).toBe(true)
  await page.keyboard.press('Escape')
  await openZoom()
  await page.getByRole('menuitem', { name: '100%', exact: true }).click()
  await compareOrRefreshGolden(REORDERED_EXPECTED,
    await captureStableAria(page, '[data-research-workbench]', scaffold.workspaceCwd), webSnapshotMode())
  await page.screenshot({ path: join(SHOTS, 'paper-reordered.png') })

  await notes.fill('Unsaved RT-2 draft')
  await addPaper('OpenVLA')
  await workbench.getByRole('textbox', { name: 'Learning notes', exact: true }).fill('OpenVLA draft')
  await library.getByRole('button', { name: 'RT-2', exact: true }).click()
  await expect.poll(() => notes.inputValue()).toBe('Unsaved RT-2 draft')
  expect(await readOrder()).toEqual(['notes', 'agent', 'pdf'])
  await page.reload({ waitUntil: 'load' })
  await expect.poll(() => notes.inputValue()).toBe('Unsaved RT-2 draft')
  expect(await readOrder()).toEqual(['notes', 'agent', 'pdf'])
  for (const panel of ['Agent chat', 'Original PDF', 'Reading notes']) {
    await workbench.getByRole('button', { name: `Collapse ${panel}`, exact: true }).click()
  }
  await workbench.getByRole('heading', { name: 'All panels are collapsed' }).waitFor()
  await workbench.getByRole('button', { name: 'Restore three panels', exact: true }).last().click()
  await expect.poll(async () => (await workbench.getByRole('img', { name: 'PDF page 1', exact: true }).boundingBox())?.width).toBeGreaterThan(100)
  await expect.poll(() => notes.inputValue()).toBe('Unsaved RT-2 draft')
  await notes.fill('# RT-2\n\nUnderstand the action token representation.')
  await workbench.getByRole('button', { name: 'Save notes', exact: true }).click()
  await workbench.getByRole('status').filter({ hasText: /^Saved$/ }).waitFor()
  await expect.poll(() => workbench.getByRole('button', { name: 'Save notes', exact: true }).isDisabled()).toBe(true)

  await workbench.getByRole('button', { name: 'Reference papers', exact: true }).click()
  const references = page.getByRole('dialog', { name: 'Reference papers', exact: true })
  await references.getByRole('checkbox', { name: 'OpenVLA', exact: true }).check()
  await references.getByRole('button', { name: 'Insert references', exact: true }).click()
  await workbench.getByText('References added to the composer', { exact: true }).waitFor()
  const catalog = await scaffold.ctx.workspaceController.researchList()
  expect(new Set([...catalog.topics.map(item => item.sessionId), ...catalog.papers.map(item => item.sessionId)]).size).toBe(3)
  expect(catalog.papers.find(item => item.title === 'RT-2')?.learning.text).toContain('action token')

  await openSettings(page, 'en')
  const settings = page.getByRole('dialog', { name: 'Settings', exact: true })
  await settings.getByRole('button', { name: 'Dark', exact: true }).click()
  await settings.getByRole('button', { name: 'Close', exact: true }).click()
  await expect.poll(() => page.locator('body').getAttribute('data-ds-dark-theme')).not.toBeNull()
  await panelControls.evaluate(async (element) => {
    await Promise.allSettled(element.getAnimations({ subtree: true }).map(animation => animation.finished))
  })
  await expect.poll(() => panelControls.getByRole('button').evaluateAll(buttons => buttons.every(button =>
    getComputedStyle(button).color === getComputedStyle(button.closest('[data-research-workbench]')!).color))).toBe(true)
  await page.screenshot({ path: join(SHOTS, 'paper-dark.png') })
  await page.reload({ waitUntil: 'load' })
  await workbench.waitFor()
  await expect.poll(() => notes.inputValue()).toContain('action token')
  await page.setViewportSize({ width: 760, height: 900 })
  expect(await legacyWorkspaces.isVisible()).toBe(false)
  const readingPanels = header.getByRole('group', { name: 'Reading panel', exact: true })
  await readingPanels.getByRole('button', { name: 'Reading notes', exact: true }).click()
  await expect.poll(() => notes.isVisible()).toBe(true)
  expect(await workbench.getByRole('region', { name: 'Agent chat', exact: true }).isVisible()).toBe(false)
  await workbench.getByRole('button', { name: 'Collapse Reading notes', exact: true }).click()
  await readingPanels.getByRole('button', { name: 'Reading notes', exact: true }).click()
  await expect.poll(() => notes.isVisible()).toBe(true)
  await expect.poll(() => notes.inputValue()).toContain('action token')
  await page.screenshot({ path: join(SHOTS, 'paper-narrow.png') })
  await page.setViewportSize({ width: 1800, height: 1080 })
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click()
  await page.mouse.move(700, 450)
  await library.waitFor({ state: 'detached' })
  await page.setViewportSize({ width: 375, height: 812 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await readingPanels.getByRole('button', { name: 'Original PDF', exact: true }).click()
  await workbench.getByRole('button', { name: 'Arrange Original PDF', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Move left', exact: true }).click()
  expect(await readingPanels.getByRole('button').allTextContents()).toEqual(['Original PDF', 'Agent chat', 'Reading notes'])
  await expect.poll(() => workbench.getByRole('img', { name: 'PDF page 1', exact: true }).isVisible()).toBe(true)
  for (const button of await readingPanels.getByRole('button').all()) {
    expect((await button.boundingBox())?.height).toBeGreaterThanOrEqual(44)
    const label = await button.locator('span:not([aria-hidden])').evaluate(element =>
      ({ text: element.textContent, width: element.clientWidth, content: element.scrollWidth }))
    expect(label.content, label.text ?? '').toBeLessThanOrEqual(label.width)
  }
  const overflow = await workbench.evaluate(element => element.scrollWidth > element.clientWidth)
  expect(overflow).toBe(false)
  expect(await readingPanels.getByRole('button', { name: 'Original PDF', exact: true }).evaluate(button =>
    getComputedStyle(button).transitionDuration)).toBe('0s')
  await page.screenshot({ path: join(SHOTS, 'paper-mobile.png') })
  await page.setViewportSize({ width: 812, height: 375 })
  await readingPanels.getByRole('button', { name: 'Reading notes', exact: true }).click()
  await expect.poll(() => notes.isVisible()).toBe(true)
  expect(await workbench.evaluate(element => element.scrollWidth > element.clientWidth)).toBe(false)
  expect(console.pageErrors).toEqual([])
}, 120_000)
